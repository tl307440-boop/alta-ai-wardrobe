package com.wardrobe.service;

import com.wardrobe.common.BusinessException;
import com.wardrobe.common.ErrorCode;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Service;
import org.springframework.web.multipart.MultipartFile;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.Base64;
import java.util.UUID;

@Service
public class StorageService {
    private static final long MAX_BYTES = 10L * 1024 * 1024; // 10MB

    private final Path rootDir;

    public StorageService(@Value("${app.storage.upload-dir:./uploads}") String uploadDir) {
        this.rootDir = Paths.get(uploadDir).toAbsolutePath().normalize();
        try {
            Files.createDirectories(this.rootDir);
        } catch (IOException e) {
            throw new IllegalStateException("Could not initialize upload directory: " + this.rootDir, e);
        }
    }

    public record StoredImage(String url, String mimeType, byte[] bytes) {}

    public StoredImage validateAndStoreImage(Long userId, MultipartFile file, String prefix) {
        if (file == null || file.isEmpty()) {
            throw new BusinessException(ErrorCode.IMAGE_INVALID, "上传图片不能为空");
        }
        if (file.getSize() > MAX_BYTES) {
            throw new BusinessException(ErrorCode.IMAGE_INVALID, "图片大小超过 10MB 上限");
        }
        byte[] bytes;
        try {
            bytes = file.getBytes();
        } catch (IOException e) {
            throw new BusinessException(ErrorCode.IMAGE_INVALID, "无法读取上传图片文件");
        }
        String detectedExt = detectImageExtensionByMagicBytes(bytes);
        if (detectedExt == null) {
            throw new BusinessException(ErrorCode.IMAGE_INVALID,
                    "文件魔数校验失败：仅支持真实 JPG / PNG / WEBP 图片，已拦截伪装或损坏文件");
        }
        String mimeType = switch (detectedExt) {
            case "png" -> "image/png";
            case "webp" -> "image/webp";
            default -> "image/jpeg";
        };
        try {
            Path userDir = rootDir.resolve("user_" + userId);
            Files.createDirectories(userDir);
            String filename = prefix + "_" + UUID.randomUUID().toString().replace("-", "") + "." + detectedExt;
            Path target = userDir.resolve(filename);
            Files.write(target, bytes);
            String publicUrl = "/uploads/user_" + userId + "/" + filename;
            return new StoredImage(publicUrl, mimeType, bytes);
        } catch (IOException e) {
            throw new BusinessException(ErrorCode.INTERNAL_ERROR, "保存图片到本地目录失败");
        }
    }

    public String toDataUri(byte[] bytes, String mimeType) {
        return "data:" + mimeType + ";base64," + Base64.getEncoder().encodeToString(bytes);
    }

    /**
     * Stores raw image bytes generated by an upstream AI image model into the user's upload directory.
     */
    public StoredImage storeGeneratedImageBytes(Long userId, byte[] bytes, String prefix) {
        if (bytes == null || bytes.length < 12) {
            throw new BusinessException(ErrorCode.AI_UPSTREAM_ERROR, "上游生图模型未返回有效图片数据");
        }
        String detectedExt = detectImageExtensionByMagicBytes(bytes);
        if (detectedExt == null) {
            detectedExt = "png";
        }
        String mimeType = switch (detectedExt) {
            case "jpg" -> "image/jpeg";
            case "webp" -> "image/webp";
            default -> "image/png";
        };
        try {
            Path userDir = rootDir.resolve("user_" + userId);
            Files.createDirectories(userDir);
            String filename = prefix + "_" + UUID.randomUUID().toString().replace("-", "") + "." + detectedExt;
            Path target = userDir.resolve(filename);
            Files.write(target, bytes);
            String publicUrl = "/uploads/user_" + userId + "/" + filename;
            return new StoredImage(publicUrl, mimeType, bytes);
        } catch (IOException e) {
            throw new BusinessException(ErrorCode.INTERNAL_ERROR, "保存生成的预览图片失败");
        }
    }

    /**
     * Safely reads an already-uploaded local image belonging to the current user (strict path traversal guard).
     */
    public StoredImage readUserLocalUpload(Long userId, String publicUrl) {
        if (publicUrl == null || !publicUrl.startsWith("/uploads/user_" + userId + "/")) {
            return null;
        }
        String relative = publicUrl.substring("/uploads/".length());
        Path resolved = rootDir.resolve(relative).normalize();
        if (!resolved.startsWith(rootDir) || !Files.exists(resolved) || !Files.isRegularFile(resolved)) {
            return null;
        }
        try {
            byte[] bytes = Files.readAllBytes(resolved);
            String ext = detectImageExtensionByMagicBytes(bytes);
            if (ext == null) return null;
            String mime = switch (ext) {
                case "png" -> "image/png";
                case "webp" -> "image/webp";
                default -> "image/jpeg";
            };
            return new StoredImage(publicUrl, mime, bytes);
        } catch (IOException e) {
            return null;
        }
    }

    /**
     * Strict magic-byte validation to block disguised non-image uploads (e.g. .txt renamed to .jpg).
     */
    public String detectImageExtensionByMagicBytes(byte[] bytes) {
        if (bytes == null || bytes.length < 12) {
            return null;
        }
        // JPEG: FF D8 FF
        if ((bytes[0] & 0xFF) == 0xFF && (bytes[1] & 0xFF) == 0xD8 && (bytes[2] & 0xFF) == 0xFF) {
            return "jpg";
        }
        // PNG: 89 50 4E 47 0D 0A 1A 0A
        if ((bytes[0] & 0xFF) == 0x89 && bytes[1] == 0x50 && bytes[2] == 0x4E && bytes[3] == 0x47
                && bytes[4] == 0x0D && bytes[5] == 0x0A && bytes[6] == 0x1A && bytes[7] == 0x0A) {
            return "png";
        }
        // WEBP: RIFF....WEBP
        if (bytes[0] == 'R' && bytes[1] == 'I' && bytes[2] == 'F' && bytes[3] == 'F'
                && bytes[8] == 'W' && bytes[9] == 'E' && bytes[10] == 'B' && bytes[11] == 'P') {
            return "webp";
        }
        return null;
    }
}
