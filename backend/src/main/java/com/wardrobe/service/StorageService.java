package com.wardrobe.service;

import com.wardrobe.common.BusinessException;
import com.wardrobe.common.ErrorCode;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Service;
import org.springframework.web.multipart.MultipartFile;

import javax.imageio.IIOImage;
import javax.imageio.ImageIO;
import javax.imageio.ImageWriteParam;
import javax.imageio.ImageWriter;
import javax.imageio.stream.MemoryCacheImageOutputStream;
import java.awt.*;
import java.awt.image.BufferedImage;
import java.io.ByteArrayInputStream;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.net.URI;
import java.net.http.HttpClient;
import java.net.http.HttpRequest;
import java.net.http.HttpResponse;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.security.MessageDigest;
import java.time.Duration;
import java.util.Base64;
import java.util.Iterator;
import java.util.Locale;
import java.util.UUID;

@Service
public class StorageService {
    private static final long MAX_BYTES = 10L * 1024 * 1024; // 10MB
    private static final long VTON_MIN_BYTES = 5L * 1024;    // 5KB
    private static final long VTON_MAX_BYTES = 5L * 1024 * 1024; // 5MB

    private final Path rootDir;

    @Value("${app.storage.frontend-public-dir:../frontend/public}")
    private String frontendPublicDir = "../frontend/public";

    @Value("${app.vton.internal-web-base-url:http://web}")
    private String internalWebBaseUrl = "http://web";

    public StorageService(@Value("${app.storage.upload-dir:./uploads}") String uploadDir) {
        this.rootDir = Paths.get(uploadDir).toAbsolutePath().normalize();
        try {
            Files.createDirectories(this.rootDir);
        } catch (IOException e) {
            throw new IllegalStateException("Could not initialize upload directory: " + this.rootDir, e);
        }
    }

    public record StoredImage(String url, String mimeType, byte[] bytes) {}

    private record ValidatedImage(byte[] bytes, String ext, String mimeType) {}

    private ValidatedImage validate(MultipartFile file) {
        if (file == null || file.isEmpty()) {
            throw new BusinessException(ErrorCode.IMAGE_INVALID, "上传图片不能为空");
        }
        if (file.getSize() > MAX_BYTES) {
            throw new BusinessException(ErrorCode.IMAGE_INVALID, "图片大小超过 10MB 上限");
        }
        byte[] bytes;
        try {
            bytes = file.getBytes();
        } catch (IOException e) {
            throw new BusinessException(ErrorCode.IMAGE_INVALID, "无法读取上传图片文件");
        }
        String detectedExt = detectImageExtensionByMagicBytes(bytes);
        if (detectedExt == null) {
            throw new BusinessException(ErrorCode.IMAGE_INVALID,
                    "文件魔数校验失败：仅支持真实 JPG / PNG / WEBP 图片，已拦截伪装或损坏文件");
        }
        String mimeType = switch (detectedExt) {
            case "png" -> "image/png";
            case "webp" -> "image/webp";
            default -> "image/jpeg";
        };
        return new ValidatedImage(bytes, detectedExt, mimeType);
    }

    /**
     * Magic-byte + size validation only (nothing is written to disk). The returned {@code url} is null.
     */
    public StoredImage validateImageOnly(MultipartFile file) {
        ValidatedImage v = validate(file);
        return new StoredImage(null, v.mimeType(), v.bytes());
    }

    public StoredImage validateAndStoreImage(Long userId, MultipartFile file, String prefix) {
        ValidatedImage validated = validate(file);
        byte[] bytes = validated.bytes();
        String detectedExt = validated.ext();
        String mimeType = validated.mimeType();
        try {
            Path userDir = rootDir.resolve("user_" + userId);
            Files.createDirectories(userDir);
            String filename = prefix + "_" + UUID.randomUUID().toString().replace("-", "") + "." + detectedExt;
            Path target = userDir.resolve(filename);
            Files.write(target, bytes);
            String publicUrl = "/uploads/user_" + userId + "/" + filename;
            return new StoredImage(publicUrl, mimeType, bytes);
        } catch (IOException e) {
            throw new BusinessException(ErrorCode.INTERNAL_ERROR, "保存图片到本地目录失败");
        }
    }

    public String toDataUri(byte[] bytes, String mimeType) {
        return "data:" + mimeType + ";base64," + Base64.getEncoder().encodeToString(bytes);
    }

    /**
     * Stores raw image bytes generated by an upstream AI image model into the user's upload directory.
     */
    public StoredImage storeGeneratedImageBytes(Long userId, byte[] bytes, String prefix) {
        if (bytes == null || bytes.length < 12) {
            throw new BusinessException(ErrorCode.AI_UPSTREAM_ERROR, "上游生图模型未返回有效图片数据");
        }
        String detectedExt = detectImageExtensionByMagicBytes(bytes);
        if (detectedExt == null) {
            detectedExt = "png";
        }
        String mimeType = switch (detectedExt) {
            case "jpg" -> "image/jpeg";
            case "webp" -> "image/webp";
            default -> "image/png";
        };
        try {
            Path userDir = rootDir.resolve("user_" + userId);
            Files.createDirectories(userDir);
            String filename = prefix + "_" + UUID.randomUUID().toString().replace("-", "") + "." + detectedExt;
            Path target = userDir.resolve(filename);
            Files.write(target, bytes);
            String publicUrl = "/uploads/user_" + userId + "/" + filename;
            return new StoredImage(publicUrl, mimeType, bytes);
        } catch (IOException e) {
            throw new BusinessException(ErrorCode.INTERNAL_ERROR, "保存生成的预览图片失败");
        }
    }

    /**
     * Safely reads an already-uploaded local image belonging to the current user (strict path traversal guard).
     */
    public StoredImage readUserLocalUpload(Long userId, String publicUrl) {
        if (publicUrl == null || !publicUrl.startsWith("/uploads/user_" + userId + "/")) {
            return null;
        }
        String relative = publicUrl.substring("/uploads/".length());
        Path resolved = rootDir.resolve(relative).normalize();
        if (!resolved.startsWith(rootDir) || !Files.exists(resolved) || !Files.isRegularFile(resolved)) {
            return null;
        }
        try {
            byte[] bytes = Files.readAllBytes(resolved);
            String ext = detectImageExtensionByMagicBytes(bytes);
            if (ext == null) return null;
            String mime = switch (ext) {
                case "png" -> "image/png";
                case "webp" -> "image/webp";
                default -> "image/jpeg";
            };
            return new StoredImage(publicUrl, mime, bytes);
        } catch (IOException e) {
            return null;
        }
    }

    /**
     * Safely resolves a garment image for AI try-on/visual extraction from either the current user's
     * upload folder or the vetted public Alta cutout catalog (/alta/pieces/<filename>).
     * Blocks all cross-user upload paths and directory traversal attempts.
     */
    public StoredImage readGarmentImageForAi(Long userId, String publicUrl) {
        if (publicUrl == null || publicUrl.isBlank()) {
            return null;
        }
        String cleanUrl = publicUrl.trim();
        if (cleanUrl.startsWith("/uploads/user_" + userId + "/")) {
            return readUserLocalUpload(userId, cleanUrl);
        }
        if (cleanUrl.startsWith("/alta/pieces/") || cleanUrl.startsWith("/alta/models/")) {
            boolean isModels = cleanUrl.startsWith("/alta/models/");
            String prefix = isModels ? "/alta/models/" : "/alta/pieces/";
            String subDir = isModels ? "models" : "pieces";
            String filename = cleanUrl.substring(prefix.length());
            if (!filename.matches("^[a-zA-Z0-9._-]+$") || filename.contains("..")) {
                return null;
            }
            Path[] candidateDirs = new Path[]{
                    Paths.get(frontendPublicDir != null ? frontendPublicDir : "../frontend/public", "alta", subDir),
                    Paths.get("frontend", "public", "alta", subDir),
                    Paths.get("..", "frontend", "public", "alta", subDir)
            };
            for (Path dir : candidateDirs) {
                Path normalizedDir = dir.toAbsolutePath().normalize();
                Path resolved = normalizedDir.resolve(filename).normalize();
                if (!resolved.startsWith(normalizedDir) || !Files.exists(resolved) || !Files.isRegularFile(resolved)) {
                    continue;
                }
                try {
                    byte[] bytes = Files.readAllBytes(resolved);
                    String ext = detectImageExtensionByMagicBytes(bytes);
                    if (ext == null) continue;
                    String mime = switch (ext) {
                        case "png" -> "image/png";
                        case "webp" -> "image/webp";
                        default -> "image/jpeg";
                    };
                    return new StoredImage(cleanUrl, mime, bytes);
                } catch (IOException ignored) {
                    // Try next candidate directory
                }
            }
        }
        return null;
    }

    public static boolean isLoopbackUrl(String url) {
        if (url == null || url.isBlank()) {
            return true;
        }
        try {
            URI uri = URI.create(url.trim());
            String scheme = uri.getScheme();
            if (!"http".equalsIgnoreCase(scheme) && !"https".equalsIgnoreCase(scheme)) {
                return true;
            }
            String host = uri.getHost();
            if (host == null || host.isBlank()) {
                return true;
            }
            String lower = host.toLowerCase(Locale.ROOT);
            if ("localhost".equals(lower) || "0.0.0.0".equals(lower)
                    || "::1".equals(lower) || "[::1]".equals(lower) || lower.startsWith("127.")) {
                return true;
            }
            return false;
        } catch (Exception e) {
            return true;
        }
    }

    /**
     * Loads an authorized local/internal image (JPG/PNG/WEBP cutout) and normalizes it into
     * an opaque white-backdrop JPEG Base64 data URI (<= 1280px) suitable for Bailian multi-image VTON.
     */
    public String prepareVtonBase64DataUri(Long userId, String assetUrl, String optionalPublicBase) {
        if (assetUrl == null || assetUrl.isBlank()) {
            return null;
        }
        String cleanAsset = assetUrl.trim();
        if (cleanAsset.startsWith("svg://")) {
            return null;
        }
        if (cleanAsset.contains("..") || cleanAsset.contains("?") || cleanAsset.contains("#")) {
            throw new BusinessException(ErrorCode.FORBIDDEN, "禁止访问非法路径资产");
        }
        String userPrefix = "/uploads/user_" + userId + "/";
        boolean isUserUpload = cleanAsset.startsWith(userPrefix);
        boolean isStaticAlta = cleanAsset.startsWith("/alta/models/") || cleanAsset.startsWith("/alta/pieces/");
        if (!isUserUpload && !isStaticAlta) {
            throw new BusinessException(ErrorCode.FORBIDDEN, "无权访问跨用户或未授权的资产");
        }

        StoredImage stored = readGarmentImageForAi(userId, cleanAsset);
        byte[] rawBytes = stored != null ? stored.bytes() : null;
        if ((rawBytes == null || rawBytes.length == 0) && isStaticAlta) {
            rawBytes = fetchInternalAssetBytes(cleanAsset, optionalPublicBase);
        }
        if (rawBytes == null || rawBytes.length < 12) {
            return null;
        }
        byte[] jpegBytes = toWhiteBackdropJpegBytes(rawBytes, 384, 1280, 0.88f, cleanAsset);
        return "data:image/jpeg;base64," + Base64.getEncoder().encodeToString(jpegBytes);
    }

    /**
     * Resolves a DashScope-ready public HTTP(S) URL for VTON (JPG/PNG only, 5KB–5MB).
     * Automatically converts .webp or out-of-spec user uploads into cached white-backdrop JPEGs under /uploads/user_{id}/.
     */
    public String preparePublicVtonImageUrl(Long userId, String assetUrl, String publicBaseUrl) {
        if (assetUrl == null || assetUrl.isBlank()) {
            return null;
        }
        if (isLoopbackUrl(publicBaseUrl)) {
            throw new IllegalStateException("未配置公网访问基地址或当前为本地回环地址，阿里云百炼无法拉取图片");
        }
        String base = trimTrailingSlash(publicBaseUrl);
        String cleanAsset = assetUrl.trim();
        if (cleanAsset.startsWith("svg://")) {
            return null;
        }
        if (cleanAsset.startsWith("http://") || cleanAsset.startsWith("https://")) {
            return cleanAsset;
        }
        if (cleanAsset.contains("..") || cleanAsset.contains("?") || cleanAsset.contains("#")) {
            throw new BusinessException(ErrorCode.FORBIDDEN, "非法的图片路径");
        }
        String userPrefix = "/uploads/user_" + userId + "/";
        boolean isUserUpload = cleanAsset.startsWith(userPrefix);
        boolean isAltaModel = cleanAsset.startsWith("/alta/models/");
        boolean isAltaPiece = cleanAsset.startsWith("/alta/pieces/");
        if (!isUserUpload && !isAltaModel && !isAltaPiece) {
            throw new BusinessException(ErrorCode.FORBIDDEN, "无权访问跨用户或非授权图片路径");
        }

        if (isAltaModel) {
            String filename = cleanAsset.substring("/alta/models/".length());
            if (!filename.matches("^[a-zA-Z0-9._-]+$")) {
                throw new BusinessException(ErrorCode.FORBIDDEN, "非法的模特资源文件名");
            }
            String lower = filename.toLowerCase(Locale.ROOT);
            if (lower.endsWith(".jpg") || lower.endsWith(".jpeg") || lower.endsWith(".png")) {
                return base + cleanAsset;
            }
            StoredImage stored = readGarmentImageForAi(userId, cleanAsset);
            byte[] rawBytes = stored != null ? stored.bytes() : fetchInternalAssetBytes(cleanAsset, base);
            if (rawBytes == null || rawBytes.length < 12) {
                return null;
            }
            return base + ensureVtonJpegCached(userId, cleanAsset, rawBytes);
        }

        if (isUserUpload) {
            StoredImage stored = readUserLocalUpload(userId, cleanAsset);
            if (stored == null) {
                return null;
            }
            boolean dashscopeFormatOk = "image/jpeg".equals(stored.mimeType()) || "image/png".equals(stored.mimeType());
            if (dashscopeFormatOk && stored.bytes().length >= VTON_MIN_BYTES && stored.bytes().length <= VTON_MAX_BYTES) {
                return base + cleanAsset;
            }
            return base + ensureVtonJpegCached(userId, cleanAsset, stored.bytes());
        }

        // /alta/pieces/
        String filename = cleanAsset.substring("/alta/pieces/".length());
        if (!filename.matches("^[a-zA-Z0-9._-]+$")) {
            throw new BusinessException(ErrorCode.FORBIDDEN, "非法的单品资源文件名");
        }
        String lower = filename.toLowerCase(Locale.ROOT);
        if (lower.endsWith(".jpg") || lower.endsWith(".jpeg") || lower.endsWith(".png")) {
            return base + cleanAsset;
        }
        StoredImage stored = readGarmentImageForAi(userId, cleanAsset);
        byte[] rawBytes = stored != null ? stored.bytes() : fetchInternalAssetBytes(cleanAsset, base);
        if (rawBytes == null || rawBytes.length < 12) {
            return null;
        }
        return base + ensureVtonJpegCached(userId, cleanAsset, rawBytes);
    }

    private byte[] fetchInternalAssetBytes(String safeRelativePath, String publicBase) {
        String[] candidates = new String[]{
                trimTrailingSlash(internalWebBaseUrl) + safeRelativePath,
                trimTrailingSlash(publicBase) + safeRelativePath
        };
        HttpClient client = HttpClient.newBuilder()
                .connectTimeout(Duration.ofSeconds(4))
                .followRedirects(HttpClient.Redirect.NORMAL)
                .build();
        for (String url : candidates) {
            if (url == null || !url.startsWith("http")) continue;
            try {
                HttpRequest req = HttpRequest.newBuilder(URI.create(url))
                        .timeout(Duration.ofSeconds(8))
                        .GET()
                        .build();
                HttpResponse<byte[]> res = client.send(req, HttpResponse.BodyHandlers.ofByteArray());
                if (res.statusCode() >= 200 && res.statusCode() < 300 && res.body() != null && res.body().length > 12) {
                    return res.body();
                }
            } catch (Exception ignored) {
                // Try next candidate
            }
        }
        return null;
    }

    public String ensureVtonJpegCached(Long userId, String cacheKey, byte[] rawBytes) {
        try {
            MessageDigest md = MessageDigest.getInstance("SHA-256");
            md.update((cacheKey + ":" + rawBytes.length).getBytes(StandardCharsets.UTF_8));
            byte[] digest = md.digest();
            StringBuilder hex = new StringBuilder();
            for (int i = 0; i < 8; i++) {
                hex.append(String.format("%02x", digest[i]));
            }
            Path userDir = rootDir.resolve("user_" + userId);
            Files.createDirectories(userDir);
            String filename = "vton_cache_" + hex + ".jpg";
            Path target = userDir.resolve(filename);
            if (Files.exists(target) && Files.size(target) >= VTON_MIN_BYTES) {
                return "/uploads/user_" + userId + "/" + filename;
            }

            byte[] jpegBytes = toWhiteBackdropJpegBytes(rawBytes, 512, 1360, 0.92f, cacheKey);
            Files.write(target, jpegBytes);
            return "/uploads/user_" + userId + "/" + filename;
        } catch (BusinessException be) {
            throw be;
        } catch (Exception e) {
            throw new IllegalStateException("转换百炼 VTON 兼容 JPG 图片失败：" + e.getMessage(), e);
        }
    }

    private byte[] toWhiteBackdropJpegBytes(byte[] rawBytes, int minDim, int maxDimLimit, float quality, String label) {
        try {
            BufferedImage src = ImageIO.read(new ByteArrayInputStream(rawBytes));
            if (src == null || src.getWidth() < 2 || src.getHeight() < 2) {
                throw new IllegalStateException("无法解码待转换图片：" + label);
            }

            int srcW = src.getWidth();
            int srcH = src.getHeight();
            int maxDim = Math.max(srcW, srcH);
            double scale = 1.0;
            if (maxDim > maxDimLimit) {
                scale = (double) maxDimLimit / maxDim;
            } else if (maxDim < minDim) {
                scale = (double) minDim / maxDim;
            }
            int drawW = Math.max(1, (int) Math.round(srcW * scale));
            int drawH = Math.max(1, (int) Math.round(srcH * scale));
            int pad = Math.max(16, (int) Math.round(Math.max(drawW, drawH) * 0.05));
            int canvasW = Math.min(maxDimLimit + 176, Math.max(360, drawW + pad * 2));
            int canvasH = Math.min(maxDimLimit + 176, Math.max(360, drawH + pad * 2));
            int drawX = (canvasW - drawW) / 2;
            int drawY = (canvasH - drawH) / 2;

            BufferedImage canvas = new BufferedImage(canvasW, canvasH, BufferedImage.TYPE_INT_RGB);
            Graphics2D g = canvas.createGraphics();
            g.setColor(Color.WHITE);
            g.fillRect(0, 0, canvasW, canvasH);
            g.setRenderingHint(RenderingHints.KEY_INTERPOLATION, RenderingHints.VALUE_INTERPOLATION_BICUBIC);
            g.setRenderingHint(RenderingHints.KEY_RENDERING, RenderingHints.VALUE_RENDER_QUALITY);
            g.drawImage(src, drawX, drawY, drawW, drawH, null);
            g.dispose();

            ByteArrayOutputStream baos = new ByteArrayOutputStream();
            Iterator<ImageWriter> writers = ImageIO.getImageWritersByFormatName("jpg");
            ImageWriter writer = writers.next();
            try (MemoryCacheImageOutputStream out = new MemoryCacheImageOutputStream(baos)) {
                ImageWriteParam param = writer.getDefaultWriteParam();
                param.setCompressionMode(ImageWriteParam.MODE_EXPLICIT);
                param.setCompressionQuality(quality);
                writer.setOutput(out);
                writer.write(null, new IIOImage(canvas, null, null), param);
            } finally {
                writer.dispose();
            }
            return baos.toByteArray();
        } catch (BusinessException be) {
            throw be;
        } catch (Exception e) {
            throw new IllegalStateException("转换百炼 VTON 兼容 JPG 图片失败：" + e.getMessage(), e);
        }
    }

    private String trimTrailingSlash(String url) {
        if (url == null) return "";
        String r = url.trim();
        while (r.endsWith("/")) {
            r = r.substring(0, r.length() - 1);
        }
        return r;
    }

    /**
     * Strict magic-byte validation to block disguised non-image uploads (e.g. .txt renamed to .jpg).
     */
    public String detectImageExtensionByMagicBytes(byte[] bytes) {
        if (bytes == null || bytes.length < 12) {
            return null;
        }
        // JPEG: FF D8 FF
        if ((bytes[0] & 0xFF) == 0xFF && (bytes[1] & 0xFF) == 0xD8 && (bytes[2] & 0xFF) == 0xFF) {
            return "jpg";
        }
        // PNG: 89 50 4E 47 0D 0A 1A 0A
        if ((bytes[0] & 0xFF) == 0x89 && bytes[1] == 0x50 && bytes[2] == 0x4E && bytes[3] == 0x47
                && bytes[4] == 0x0D && bytes[5] == 0x0A && bytes[6] == 0x1A && bytes[7] == 0x0A) {
            return "png";
        }
        // WEBP: RIFF....WEBP
        if (bytes[0] == 'R' && bytes[1] == 'I' && bytes[2] == 'F' && bytes[3] == 'F'
                && bytes[8] == 'W' && bytes[9] == 'E' && bytes[10] == 'B' && bytes[11] == 'P') {
            return "webp";
        }
        return null;
    }
}
